"""生成物料导入测试文件（临时验证脚本）

产出三个文件：
  mat_ok.xlsx     —— 3 行全部合法（编码留空，应由编号规则自动生成）
  mat_bad.xlsx    —— 4 行，其中第 3 行分类不存在、第 4 行名称与库内重复
  mat_empty.xlsx  —— 只有表头，应报「没有数据行」
"""
import openpyxl
from openpyxl import Workbook

# 注意：Git Bash 的 /tmp 与 Windows Python 看到的 /tmp 不是同一目录，
# 统一落到项目 backup 目录，双方路径一致。
BASE = r'D:\code\java\java_study\erp-system\.workbuddy\backup'

HEADER = ['物料编码', '物料名称', '简称', '规格', '分类', '计量单位',
          '采购价', '销售价', '零售价', '最低库存', '最高库存', '状态', '备注']


def build(name, rows):
    path = BASE + '\\' + name
    wb = Workbook()
    ws = wb.active
    ws.title = '物料'
    ws.append(HEADER)
    for r in rows:
        ws.append(r)
    wb.save(path)
    print(f"written {path}  ({len(rows)} 数据行)")


# 1) 全部合法：编码留空 -> 自动生成；分类/单位按名称匹配
build('mat_ok.xlsx', [
    ['', '测试物料甲', '甲', '100*100', '原材料', '千克', 10.5, 15, 18, 1, 100, '启用', '导入测试'],
    ['', '测试物料乙', '', '200*200', '成品', '个', 20, 30, 35, 2, 200, '禁用', '导入测试'],
    ['', '测试物料丙', '丙', '', '辅料', '套', 5, 8, 9, 0, 50, '', '状态留空走默认启用'],
])

# 2) 含错误：第 3 行分类不存在，第 4 行名称与库内已有「纸箱」重复
build('mat_bad.xlsx', [
    ['', '测试物料丁', '', '', '原材料', '千克', 1, 2, 3, 0, 10, '启用', ''],
    ['', '测试物料戊', '', '', '成品', '个', 1, 2, 3, 0, 10, '启用', ''],
    ['', '测试物料己', '', '', '不存在的分类', '个', 1, 2, 3, 0, 10, '启用', ''],
    ['', '纸箱', '', '', '包装物', '个', 1, 2, 3, 0, 10, '启用', '名称与库内重复'],
])

# 3) 只有表头
build('mat_empty.xlsx', [])

# 4) 文件内编码重复（第 3、4 行编码相同）
build('mat_dupcode.xlsx', [
    ['', '测试物料庚', '', '', '原材料', '千克', 1, 2, 3, 0, 10, '启用', ''],
    ['MAT999999', '测试物料辛', '', '', '成品', '个', 1, 2, 3, 0, 10, '启用', ''],
    ['MAT999999', '测试物料壬', '', '', '成品', '个', 1, 2, 3, 0, 10, '启用', '重复编码'],
])
