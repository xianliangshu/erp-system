CUS_HEADER = ['客户编号', '客户名称', '简称', '类型', '级别', '联系人', '联系电话',
              '邮箱', '地址', '结算方式', '账期(天)', '状态', '备注']
SUP_HEADER = ['供应商编号', '供应商名称', '简称', '类型', '信用等级', '联系人', '联系电话',
              '邮箱', '地址', '结算方式', '账期(天)', '开户行', '银行账号', '税号', '状态', '备注']


def build(name, header, sheet, rows):
    path = BASE + '\\' + name
    wb = Workbook()
    ws = wb.active
    ws.title = sheet
    ws.append(header)
    for r in rows:
        ws.append(r)
    wb.save(path)
    print(f"written {path}  ({len(rows)} 数据行)")


